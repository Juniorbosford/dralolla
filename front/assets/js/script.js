/**
 * localStorage/sessionStorage podem lançar erro em navegação privada
 * ou com cookies bloqueados — por isso o acesso passa por aqui.
 */
const storage = {
    get(store, key) {
        try { return window[store].getItem(key); } catch (e) { return null; }
    },
    set(store, key, value) {
        try { window[store].setItem(key, value); } catch (e) { /* ignora */ }
    }
};

/**
 * Idioma
 * PT = texto original do HTML
 * EN = traduções do objeto translations.en
 */
function initLanguage() {
    const savedLang = getCurrentLanguage();
    const langButtons = document.querySelectorAll('[data-lang]');

    if (savedLang === 'en') {
        applyTranslations('en');
    } else {
        document.documentElement.lang = 'pt-BR';
    }

    langButtons.forEach(button => {
        button.classList.toggle('active', button.getAttribute('data-lang') === savedLang);

        button.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            if (lang === getCurrentLanguage()) return;

            storage.set('localStorage', 'siteLanguage', lang);

            // PT é o texto original do HTML: recarregar restaura tudo
            if (lang === 'pt') {
                location.reload();
                return;
            }

            langButtons.forEach(btn => btn.classList.toggle('active', btn === this));
            applyTranslations('en');
        });
    });
}

function applyTranslations(lang) {
    const dict = translations[lang];
    if (!dict) return;

    document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';

    // Inclui o <title>, que usa data-i18n com a chave do título de cada página
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (Object.prototype.hasOwnProperty.call(dict, key)) {
            element.textContent = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (Object.prototype.hasOwnProperty.call(dict, key)) {
            element.setAttribute('placeholder', dict[key]);
        }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(element => {
        const key = element.getAttribute('data-i18n-html');
        if (Object.prototype.hasOwnProperty.call(dict, key)) {
            element.innerHTML = dict[key];
        }
    });
}

function getCurrentLanguage() {
    return storage.get('localStorage', 'siteLanguage') === 'en' ? 'en' : 'pt';
}

function t(key) {
    const lang = getCurrentLanguage();
    return translations?.[lang]?.[key] || translations?.pt?.[key] || key;
}

/**
 * Validações (mesmas regras do servidor)
 */
function isValidEmail(value) {
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(value).trim());
}

function isValidPhone(value) {
    const digits = String(value).replace(/\D/g, '');
    return digits.length >= 10 && digits.length <= 13;
}

/**
 * Envia JSON para a API e trata erros com mensagens traduzidas
 */
async function postJson(url, payload) {
    let response;
    try {
        response = await fetch(url, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(payload)
        });
    } catch (e) {
        throw new Error(t('alertSendError'));
    }

    const result = await response.json().catch(() => ({}));

    if (response.status === 429) throw new Error(t('alertTooMany'));
    if (!response.ok || !result.ok) {
        // Mensagens do servidor estão em português
        const serverMsg = getCurrentLanguage() === 'pt' ? result.message : null;
        throw new Error(serverMsg || t('alertSendError'));
    }
    return result;
}

function setLoading(btn, loading, originalContent) {
    if (loading) {
        btn.innerHTML = `<i class="fas fa-spinner fa-spin"></i> ${t('sending')}`;
        btn.classList.add('btn-loading');
        btn.disabled = true;
    } else {
        btn.innerHTML = originalContent;
        btn.classList.remove('btn-loading');
        btn.disabled = false;
    }
}

