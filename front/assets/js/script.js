/**
 * Popup de contato
 */
function initPopup() {
    const popup = document.getElementById('popupOverlay');
    const closeBtn = document.getElementById('popupClose');
    const skipBtn = document.getElementById('popupSkip');
    const form = document.getElementById('popupForm');

    if (popup && !storage.get('sessionStorage', 'popupClosed')) {
        setTimeout(() => {
            popup.classList.add('active');
        }, 5000);
    }

    function closePopup() {
        if (popup) {
            popup.classList.remove('active');
            storage.set('sessionStorage', 'popupClosed', 'true');
        }
    }

    if (closeBtn) closeBtn.addEventListener('click', closePopup);
    if (skipBtn) skipBtn.addEventListener('click', closePopup);

    if (popup) {
        popup.addEventListener('click', function(e) {
            if (e.target === popup) closePopup();
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape' && popup.classList.contains('active')) closePopup();
        });
    }

    if (form) {
        form.addEventListener('submit', async function(e) {
            e.preventDefault();

            const contactInput = form.querySelector('.popup-input');
            const value = contactInput ? contactInput.value.trim() : '';

            if (!value) {
                alert(t('alertInvalidContact'));
                return;
            }

            if (!isValidPhone(value) && !isValidEmail(value)) {
                alert(t('alertInvalidFormat'));
                return;
            }

            const btn = form.querySelector('button[type="submit"]');
            const originalContent = btn.innerHTML;
            setLoading(btn, true);

            try {
                await postJson('/api/leads', {
                    contact: value,
                    page: window.location.pathname,
                    source: 'popup_contato'
                });
                alert(t('alertPopupSuccess'));
                form.reset();
                closePopup();
            } catch (error) {
                alert(error.message);
            } finally {
                setLoading(btn, false, originalContent);
            }
        });
    }
}

/**
 * Menu Mobile - Toggle
 */
function initMobileMenu() {
    const menuToggle = document.getElementById('menuToggle');
    const navMenu = document.getElementById('navMenu');

    if (!menuToggle || !navMenu) return;

    const spans = menuToggle.querySelectorAll('span');

    function setOpen(open) {
        navMenu.classList.toggle('active', open);
        menuToggle.setAttribute('aria-expanded', String(open));
        if (spans.length < 3) return;
        spans[0].style.transform = open ? 'rotate(45deg) translate(5px, 5px)' : 'none';
        spans[1].style.opacity = open ? '0' : '1';
        spans[2].style.transform = open ? 'rotate(-45deg) translate(5px, -5px)' : 'none';
    }

    menuToggle.addEventListener('click', function() {
        setOpen(!navMenu.classList.contains('active'));
    });

    menuToggle.addEventListener('keydown', function(e) {
        if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            setOpen(!navMenu.classList.contains('active'));
        }
    });

    navMenu.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', () => setOpen(false));
    });
}

/**
 * Formulário de Agendamento
 */
function initFormSubmission() {
    const form = document.getElementById('agendamentoForm');
    if (!form) return;

    form.addEventListener('submit', async function(e) {
        e.preventDefault();

        const data = Object.fromEntries(new FormData(form).entries());

        if (!data.nome?.trim() || !data.telefone || !data.email || !data.servico) {
            alert(t('alertRequiredFields'));
            return;
        }

        if (!isValidPhone(data.telefone)) {
            alert(t('alertInvalidPhone'));
            return;
        }

        if (!isValidEmail(data.email)) {
            alert(t('alertInvalidEmail'));
            return;
        }

        const btn = form.querySelector('button[type="submit"]');
        const originalContent = btn.innerHTML;
        setLoading(btn, true);

        try {
            await postJson('/api/agendamentos', {
                ...data,
                page: window.location.pathname,
                source: 'formulario_agendamento'
            });
            alert(t('alertScheduleSuccess'));
            form.reset();
        } catch (error) {
            alert(error.message);
        } finally {
            setLoading(btn, false, originalContent);
        }
    });
}

/**
 * Data preferencial: não permite escolher dias que já passaram
 */
function initDateMin() {
    const dateInput = document.getElementById('data');
    if (!dateInput) return;

    const now = new Date();
    const local = new Date(now.getTime() - now.getTimezoneOffset() * 60000);
    dateInput.min = local.toISOString().slice(0, 10);
}

/**
 * Smooth Scroll para links internos
 */
function initSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(link => {
        link.addEventListener('click', function(e) {
            const href = this.getAttribute('href');
            if (href === '#' || href === '#!') return;

            const target = document.querySelector(href);
            if (!target) return;

            e.preventDefault();
            const header = document.querySelector('.header');
            const headerHeight = header ? header.offsetHeight : 0;
            const targetPosition = target.getBoundingClientRect().top + window.pageYOffset - headerHeight;

            window.scrollTo({ top: targetPosition, behavior: 'smooth' });
        });
    });
}

/**
 * Animações ao scroll (opcional — não está ativa).
 * Para ativar, adicione initScrollAnimations() no DOMContentLoaded lá em cima.
 */
function initScrollAnimations() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('animate-in');
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

    document.querySelectorAll('.service-card, .testimonial-card').forEach(el => observer.observe(el));
}

/**
 * Máscara de telefone: (81) 99999-9999 ou (81) 3333-4444
 */
function initPhoneMask() {
    document.querySelectorAll('input[type="tel"]').forEach(input => {
        input.addEventListener('input', function(e) {
            let value = e.target.value.replace(/\D/g, '').slice(0, 11);

            if (value.length > 10) {
                value = value.replace(/^(\d\d)(\d{5})(\d{4}).*/, '($1) $2-$3');
            } else if (value.length > 6) {
                value = value.replace(/^(\d\d)(\d{4})(\d{0,4}).*/, '($1) $2-$3');
            } else if (value.length > 2) {
                value = value.replace(/^(\d\d)(\d{0,5}).*/, '($1) $2');
            } else if (value.length > 0) {
                value = value.replace(/^(\d*)/, '($1');
            }

            e.target.value = value;
        });
    });
}
